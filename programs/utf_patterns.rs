fn main() {
    let s = "one, two;three  four,five";
    let parts: Vec<&str> = s.split(&[',', ';', ' '][..]).collect();
    println!("{:?}", parts);
    let parts2: Vec<&str> = s.split([',', ';']).collect();
    println!("{:?}", parts2);
    let parts3: Vec<&str> = s.split(|c: char| !c.is_alphabetic()).filter(|p| !p.is_empty()).collect();
    println!("{:?}", parts3);
    let csv = "a=>b=>c=>";
    println!("{:?}", csv.split("=>").collect::<Vec<_>>());
    println!("{:?}", csv.split_terminator("=>").collect::<Vec<_>>());
    println!("{:?}", "日本-語-テ".split('-').collect::<Vec<_>>());
    println!("{:?}", "a🦀b🦀c".split('🦀').collect::<Vec<_>>());
    println!("{:?}", "a1b22c333".split(char::is_numeric).collect::<Vec<_>>());
    println!("{:?}", "k:v:w".splitn(2, ':').collect::<Vec<_>>());
    println!("{:?}", "k:v:w".rsplitn(2, ':').collect::<Vec<_>>());
    println!("{:?}", "k:v:w".split_once(':'));
    println!("{:?}", "k:v:w".rsplit_once(':'));
    println!("{:?}", "aXbYc".rsplit(|c: char| c.is_uppercase()).collect::<Vec<_>>());
    let text = "the cat sat on the mat with the hat";
    println!("{}", text.matches("the").count());
    println!("{:?}", text.match_indices("at").collect::<Vec<_>>());
    println!("{:?}", "é1é2é".match_indices('é').collect::<Vec<_>>());
    println!("{:?}", "a1b2".matches(char::is_numeric).collect::<Vec<_>>());
    println!("{:?}", text.rmatch_indices("the").map(|(i, _)| i).collect::<Vec<_>>());
    println!("{:?}", "xxhixx".trim_matches('x'));
    println!("{:?}", "123abc456".trim_start_matches(char::is_numeric));
    println!("{:?}", "123abc456".trim_end_matches(|c: char| c.is_ascii_digit()));
    println!("{:?}", "  ünï  ".trim());
    println!("{:?}", "prefix_body".strip_prefix("prefix_"));
    println!("{:?}", "body.rs".strip_suffix(".txt"));
    println!("{}", "hello".replace('l', "L"));
    println!("{}", "日本日本".replacen("日", "月", 1));
    println!("{}", "a-b_c".replace(&['-', '_'][..], " "));
    println!("{}", "abc".contains(char::is_uppercase));
    println!("{}", "abc".starts_with(|c: char| c == 'a'));
    println!("{}", "abc".ends_with(['x', 'c']));
    println!("{:?}", "lines\nof\r\ntext\n".lines().collect::<Vec<_>>());
}
