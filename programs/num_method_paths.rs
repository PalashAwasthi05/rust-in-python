fn main() {
    println!("{} {} {}", u32::max(3, 5), i32::abs(-3), f64::max(1.5, -2.0));
    println!("{} {}", u64::pow(2, 10), i32::wrapping_add(i32::MAX, 1));
    println!("{}", u8::is_ascii_digit(&b'7'));
    let v = vec![1u8, 2, 3];
    let w: Vec<u32> = v.iter().copied().map(u32::from).collect();
    println!("{:?}", w);
    let n = vec![-3i64, 4, -5];
    let a: Vec<i64> = n.iter().copied().map(i64::abs).collect();
    println!("{:?}", a);
    let s = [u32::MAX, 5, 7].iter().copied().fold(0, u32::wrapping_add);
    println!("{}", s);
    let r: Vec<f64> = [4.0, 9.0, 2.0].iter().copied().map(f64::sqrt).collect();
    println!("{:?}", r);
    let x = 10u32;
    let y = &x;
    println!("{:?} {:?}", y.checked_sub(11), y.checked_add(*y));
    println!("{}", y.pow(2) + y.count_ones());
    let refs = vec![&1i32, &-2, &3];
    let total: i32 = refs.iter().map(|r| r.abs()).sum();
    println!("{}", total);
    let m = n.iter().map(|x| x.rem_euclid(3)).collect::<Vec<_>>();
    println!("{:?}", m);
    let mx = n.iter().copied().fold(i64::MIN, i64::max);
    println!("{}", mx);
    let mn = r.iter().copied().fold(f64::INFINITY, f64::min);
    println!("{}", mn);
    let shifted: Vec<u16> = v.iter().map(|&b| (b as u16) << 8 | 0xFF).collect();
    println!("{:?}", shifted);
    let parsed: Result<Vec<i32>, _> = "1,-2,x".split(',').map(str::parse::<i32>).collect();
    println!("{:?}", parsed.is_err());
    let parsed: Vec<u8> = "1 2 255".split_whitespace().map(|s| s.parse().unwrap()).collect();
    println!("{:?}", parsed);
    let sum_sq: u64 = (1..=10u64).map(|i| i.pow(2)).sum();
    println!("{}", sum_sq);
    let any_neg = n.iter().any(|&x| x.is_negative());
    println!("{}", any_neg);
    let signs: Vec<i64> = n.iter().map(|x| x.signum()).collect();
    println!("{:?}", signs);
    let maxf = [1.5f64, f64::NAN, 3.0].iter().copied().fold(f64::MIN, f64::max);
    println!("{}", maxf);
    let total_f: f64 = [0.1f64; 10].iter().sum();
    println!("{}", total_f);
    let prod_f: f32 = [1.1f32; 5].iter().product();
    println!("{}", prod_f);
    let bytes = 0x01020304u32.to_le_bytes();
    let rebuilt = bytes.iter().rev().fold(0u32, |acc, &b| acc << 8 | b as u32);
    println!("{:#x}", rebuilt);
    println!("{}", i8::try_from(200u8).unwrap_or(i8::MAX));
    println!("{}", u16::MAX.to_string().parse::<u32>().unwrap() + 1);
    let mut counter: [usize; 10] = [0; 10];
    for d in 12345678901234567890u64.to_string().chars() {
        counter[d.to_digit(10).unwrap() as usize] += 1;
    }
    println!("{:?}", counter);
    let text = b"Hello, World 42!";
    let digits: u32 = text.iter().filter(|b| b.is_ascii_digit()).map(|&b| (b - b'0') as u32).sum();
    let upper: Vec<u8> = text.iter().map(|b| b.to_ascii_uppercase()).collect();
    let letters = text.iter().filter(|b| b.is_ascii_alphabetic()).count();
    println!("{} {} {}", digits, String::from_utf8(upper).unwrap(), letters);
    let mut byte = b'q';
    byte.make_ascii_uppercase();
    println!("{} {} {}", byte as char, b'A'.eq_ignore_ascii_case(&b'a'), 200u8.is_ascii());
}
