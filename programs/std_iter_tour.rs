// A tour of iterator, slice, string and Option APIs, one call per line.
use std::collections::*;
fn main() {
    let v = vec![1, 2, 3, 4, 5, 6];
    println!("{:?}", v.iter().rev().skip(1).step_by(2).collect::<Vec<_>>());
    println!("{:?}", v.split(|x| x % 3 == 0).collect::<Vec<_>>());
    println!("{:?}", v.iter().map(|x| x * 2).rev().collect::<Vec<_>>());
    println!("{:?}", v.iter().max_by(|a, b| a.cmp(b)));
    println!("{:?}", v.iter().copied().reduce(|a, b| a.max(b)));
    println!("{:?}", v.chunks(4).map(|c| c.to_vec()).collect::<Vec<_>>());
    println!("{:?}", v.iter().sum::<i32>() as f64 / v.len() as f64);
    println!("{:?}", v.iter().skip(10).next());
    println!("{:?}", v.iter().take(2).chain(v.iter().skip(4)).collect::<Vec<_>>());
    println!("{:?}", v.iter().zip(v.iter().skip(1)).map(|(a, b)| b - a).collect::<Vec<_>>());
    println!("{:?}", v.iter().flat_map(|&x| vec![x; x as usize % 3]).collect::<Vec<_>>());
    println!("{:?}", v.iter().filter(|&&x| x > 2).min());
    println!("{:?}", v.iter().copied().partition::<Vec<_>, _>(|x| *x < 3));
    println!("{:?}", (1..=4).map(|x| x * x).collect::<HashSet<_>>().len());
    println!("{:?}", (1..=4).map(|i| (i, i * 10)).collect::<BTreeMap<_, _>>());
    println!("{:?}", "a=1;b=2".split(';').map(|kv| kv.split_once('=').unwrap()).collect::<HashMap<_, _>>().len());
    println!("{:?}", v.last().copied().unwrap_or_default());
    println!("{:?}", v.iter().rev().position(|&x| x == 2));
    println!("{:?}", v.iter().count());
    println!("{:?}", v.windows(2).all(|w| w[0] < w[1]));
    println!("{:?}", v.iter().is_sorted());
    println!("{:?}", v.contains(&3));
    println!("{:?}", v.iter().any(|&x| x == 7));
    println!("{:?}", v.iter().cloned().cycle().skip(4).take(4).collect::<Vec<_>>());
    println!("{:?}", v.iter().enumerate().filter(|(i, _)| i % 2 == 0).map(|(_, x)| x).collect::<Vec<_>>());
    println!("{:?}", std::iter::once(0).chain(v.iter().copied()).collect::<Vec<_>>());
    println!("{:?}", std::iter::repeat_with(|| 7).take(2).collect::<Vec<_>>());
    println!("{:?}", (0..3).flat_map(|i| (0..i).map(move |j| (i, j))).collect::<Vec<_>>());
    println!("{:?}", v.iter().map(|x| x.to_string()).collect::<String>());
    println!("{:?}", vec!["a", "b"].concat());
    println!("{:?}", vec![String::from("x"), String::from("y")].join("+"));
    println!("{:?}", "abc".chars().map(|c| c.to_ascii_uppercase()).rev().collect::<String>());
    println!("{:?}", "a b c".split(' ').rev().collect::<Vec<_>>().join(" "));
    println!("{:?}", "Hello".char_indices().map(|(i, c)| format!("{}{}", i, c)).collect::<Vec<_>>());
    println!("{:?}", "hello".find("ll").map(|i| &"hello"[i..]));
    println!("{:?}", "x".repeat(3) + "y");
    println!("{:?}", "AbC".chars().all(char::is_alphabetic));
    println!("{:?}", "12".chars().map(|c| c as u8 - b'0').collect::<Vec<_>>());
    println!("{:?}", i32::MAX.checked_add(1).is_none());
    println!("{:?}", (-5i32).pow(2));
    println!("{:?}", 7 / 2 * 2);
    println!("{:?}", 2f64.powi(-2));
    println!("{:?}", (1u64 << 63).to_string().len());
    println!("{:?}", u32::try_from(-1i32).is_err());
    println!("{:?}", 10_i64.abs_diff(-10));
    println!("{:?}", f64::MAX.min(1.0));
    println!("{:?}", (0.1f64 + 0.2).to_string());
    println!("{:?}", 1.0f64 / 3.0);
    println!("{:?}", 100.0f64.ln() / 10f64.ln());
    println!("{:?}", 9.99f64 as u8);
    println!("{:?}", u8::MAX.wrapping_add(1));
    println!("{:?}", i16::from_str_radix("-7fff", 16));
    println!("{:?}", Some(3).map(|x| x + 1).filter(|x| x % 2 == 0).unwrap_or(0));
    println!("{:?}", Some(2).iter().map(|x| x * 3).sum::<i32>());
    println!("{:?}", Ok::<i32, String>(1).and_then(|x| Err::<i32, String>(format!("e{}", x))));
    println!("{:?}", None::<i32>.or_else(|| Some(1)).xor(None));
    println!("{:?}", Some((1, 'a')).unzip());
    println!("{:?}", Some(5).take_if(|x| *x > 3));
    println!("{:?}", vec![Some(1), None].into_iter().flatten().count());
    println!("{:?}", Err::<(), &str>("x").unwrap_or_else(|e| println!("handled {}", e)));
    println!("{:?}", [3, 1, 2].iter().max().copied());
    let mut s = String::from("hello world");
    s.replace_range(0..5, "HELLO");
    let d: String = s.drain(..6).collect();
    println!("{:?} {:?}", s, d);
    println!("{:?}", s.char_indices().nth(2));
    println!("{:?}", String::from_iter(['a', 'b']));
    println!("{:?}", s.chars().filter(|c| "aeiou".contains(*c)).count());
    println!("{:?}", format!("{:>8}", format!("{:.1}%", 12.345)));
    println!("{:?}", format!("{:^+9.2e}", 1234.5));
    println!("{:?}", format!("{:#?}", Some(Some(1))));
}
