fn main() {
    println!("{:e}", 1234.5);
    println!("{:E}", 1234.5);
    println!("{:e}", 0.00012);
    println!("{:e}", 1.0);
    println!("{:e}", 0.0);
    println!("{:e}", -0.0);
    println!("{:e}", 1e100);
    println!("{:e}", f64::MAX);
    println!("{:e}", f64::MIN_POSITIVE);
    println!("{:.2e}", 1234.5);
    println!("{:.0e}", 1500.0);
    println!("{:.0e}", 2500.0);
    println!("{:.3E}", 0.000123456);
    println!("{:e}", 1234);
    println!("{:e}", 100u32);
    println!("{:E}", 1200000i64);
    println!("{:.1e}", 15);
    println!("{:.1e}", 25);
    println!("{:e}", -42);
    println!("{:12e}|", 1.5);
    println!("{:<12e}|", 1.5);
    println!("{:+e}", 1.5);
    println!("{:012e}", 1.5);
    println!("{:e}", f64::NAN);
    println!("{:e}", f64::INFINITY);
    println!("{:e}", 0.1f32);
    println!("{:e}", 1e-7);
    println!("{:.3e}", 0.0);
    println!("{:e}", 0);
}
