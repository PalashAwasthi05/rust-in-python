fn main() {
    println!("[{:>10}]", "right");
    println!("[{:<10}]", "left");
    println!("[{:^10}]", "mid");
    println!("[{:^11}]", "mid");
    println!("[{:*^9}]", "x");
    println!("[{:-<8}]", "ab");
    println!("[{:#>6}]", 42);
    println!("[{:10}]", 42);
    println!("[{:10}]", "str");
    println!("[{:<5}]", 7);
    println!("[{:^7}]", -3);
    println!("[{:05}]", 42);
    println!("[{:05}]", -42);
    println!("[{:+}]", 42);
    println!("[{:+}]", -42);
    println!("[{:+}]", 0);
    println!("[{:+.2}]", 3.14159);
    println!("[{:+}]", 1.0);
    println!("[{:+?}]", 1.0);
    println!("[{:08.3}]", 3.14159);
    println!("[{:08.3}]", -3.14159);
    println!("[{:+08.2}]", 2.5);
    println!("[{:<08}]", 5);
    println!("[{:^08}]", 5);
    println!("[{:>3}]", "toolong");
    println!("[{:5}]", true);
    println!("[{:>5}]", 'c');
    println!("[{:^5}]", 'é');
    println!("[{:>6}]", "héllo");
    println!("[{:>4}]", "日本");
    let w = 12;
    let name = "dyn";
    println!("[{:>w$}]", name);
    println!("[{:>1$}]", name, 7);
    println!("[{:>width$}]", name, width = 9);
    println!("[{:^width$.prec$}]", 2.0f64.sqrt(), width = 12, prec = 4);
    println!("[{:>1$.2$}]", 1.23456, 10, 3);
    println!("[{:?}]", "pad");
    println!("[{:>8?}]", "pad");
    println!("[{:<8?}]", 'p');
    println!("[{:>10?}]", Some(1));
    println!("[{:6?}]", 1.5);
    println!("[{:06?}]", -1.5);
    println!("[{:>8}]", String::from("owned"));
    println!("[{:🦀^9}]", "rs");
    println!("[{:08}]", f64::NAN);
    println!("[{:08}]", -f64::INFINITY);
    println!("[{:+}]", -0.0);
    println!("[{:5}]", -0.0);
    println!("[{:>10?}]", vec![1, 2]);
    println!("[{:>6?}]", (1, 2));
}
