fn main() {
    let c = '🦀';
    let mut buf = [0u8; 4];
    let encoded = c.encode_utf8(&mut buf);
    println!("{} {}", encoded, encoded.len());
    println!("{:?}", buf);
    println!("{}", "héllo".encode_utf16().count());
    println!("{}", "🦀".encode_utf16().count());
    let utf16: Vec<u16> = "aé🦀".encode_utf16().collect();
    println!("{:?}", utf16);
    println!("{}", String::from_utf16(&utf16).unwrap());
    println!("{}", String::from_utf16_lossy(&[0x61, 0xd800, 0x62]));
    println!("{}", 'é'.escape_unicode());
    println!("{}", '\n'.escape_default());
    println!("{}", 'é'.escape_default());
    println!("{}", "tab\t é\u{301}".escape_debug());
    println!("{}", "tab\t é".escape_default());
    println!("{}", "abc".escape_unicode());
    println!("{:?}", ['\u{a0}', '\u{200b}', '\u{feff}', '\u{7}', 'a']);
    println!("{:?}", "\u{a0}x\u{ad}");
    let s: String = vec!['h', 'é', '!'].iter().collect();
    println!("{}", s);
    let t = String::from_iter(['a', 'b']);
    println!("{}", t);
    let nth = "日本語".chars().nth(1);
    println!("{:?}", nth);
    let skip: String = "Grüße".chars().skip(2).take(2).collect();
    println!("{}", skip);
    let upper_count = "ÀbÇdÉ".chars().filter(|c| c.is_uppercase()).count();
    println!("{}", upper_count);
    println!("{}", 'a'.to_string() + "é");
    println!("{}", char::from_u32(0x10FFFF).is_some());
    println!("{}", ('a' as u8 + 25) as char);
    println!("{:?}", "abc".char_indices().rev().next());
    println!("{}", "ǅ".to_lowercase());
    println!("{}", "ﬃ".to_uppercase());
    println!("{}", "ΣΑΣ".to_lowercase());
    println!("{:?}", 'A'.cmp(&'é'));
    println!("{}", "x".repeat(3) + &"é".repeat(2));
}
