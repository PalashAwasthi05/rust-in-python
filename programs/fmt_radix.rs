fn main() {
    println!("{:x} {:X} {:o} {:b}", 255, 255, 8, 5);
    println!("{:#x} {:#X} {:#o} {:#b}", 255, 255, 8, 5);
    println!("{:x}", -1i8);
    println!("{:x}", -1i16);
    println!("{:x}", -1i32);
    println!("{:x}", -1i64);
    println!("{:x}", -1i128);
    println!("{:b}", -2i8);
    println!("{:o}", -8i32);
    println!("{:#X}", -255i32);
    println!("{:#010b}", 5);
    println!("{:#010x}", 255);
    println!("{:010x}", 255);
    println!("{:#06x}", 0xab);
    println!("{:08b}", 5u8);
    println!("{:>8b}|", 5u8);
    println!("{:<#8x}|", 31);
    println!("{:^#12b}|", 10);
    println!("{:x}", u64::MAX);
    println!("{:x}", u128::MAX);
    println!("{:#b}", 0);
    println!("{:#x}", isize::MIN);
    println!("{:x}", -1isize);
    println!("{:X}", 0xdead_beef_u32);
    println!("{:x?}", vec![10, 255]);
    println!("{:#x?}", 255);
    println!("{:X?}", (10, 11));
    println!("{:02x}{:02x}{:02x}", 1, 171, 255);
    let bytes: Vec<u8> = vec![0, 15, 16, 255];
    let hex: Vec<String> = bytes.iter().map(|b| format!("{:02X}", b)).collect();
    println!("{}", hex.join(":"));
    println!("{:+x}", 15);
    let n: i16 = -300;
    println!("{:x} {:b}", n, n);
    let m = -5;
    println!("{:x}", m);
    println!("{:x}", -5i64 as u8);
    println!("{:#x}", 'a' as u32);
}
